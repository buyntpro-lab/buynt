/**
 * Obtiene URL de imagen para un item demo
 * Intenta match exacto con categoría, luego busca keywords en título
 * Si nada coincide, usa default
 */
export function getImageUrlForDemo(category?: string, title?: string): string {
  if (!category && !title) return DEMO_IMAGE_URLS.default;

  // 1. Intenta match exacto con categoría
  if (category && DEMO_IMAGE_URLS[category]) {
    return DEMO_IMAGE_URLS[category];
  }

  // 2. Busca keywords en el título
  if (title) {
    const titleLower = title.toLowerCase();
    for (const [key, url] of Object.entries(DEMO_IMAGE_URLS)) {
      if (key !== 'default' && titleLower.includes(key.toLowerCase())) {
        return url;
      }
    }
  }

  // 3. Fallback
  return DEMO_IMAGE_URLS.default;
}
